def main():
    print("== family gate battery: model-VHC under first-order families ==")
    print("   (Note M path P15; semantics and laws in Note M, Prop M.9)")
    print()
    collect = []
    total_p = total_f = 0
    tee = Tee("family_gate_results.txt")

    saved = sys.stdout
    sys.stdout = tee
    try:
        models = base_models()
        eps = eps_factor(with_seed=True)
        ep2 = eps2_factor(with_seed=True)

        for (name, hc, T_hint, note) in models:
            print("-- model: %s (%s)" % (name, note))
            _t0 = time.time()
            p, f = run_family(hc, eps, collect=collect, T_hint=T_hint)
            print("      (elapsed %.1f s)" % (time.time() - _t0))
            total_p += p
            total_f += f
            print()

        print("-- two-parameter first-order family (dim N^1 = 2), anchor models")
        for (name, hc, T_hint, note) in models[:3]:
            print("-- model: %s" % name)
            _t0 = time.time()
            p, f = run_family(hc, ep2, prefix="2par.", collect=collect, T_hint=T_hint)
            print("      (elapsed %.1f s)" % (time.time() - _t0))
            total_p += p
            total_f += f
            print()

        print("-- negative control: family direction with NO algebraic seed")
        for (name, hc, T_hint, note) in [models[1], models[2]]:
            print("-- model: %s" % name)
            _t0 = time.time()
            p, f = run_negative_control(hc, collect=collect, T_hint=T_hint)
            print("      (elapsed %.1f s)" % (time.time() - _t0))
            total_p += p
            total_f += f
            print()
    finally:
        sys.stdout = saved

    print("== battery summary: %d checks, %d PASS, %d FAIL =="
          % (len(collect), total_p, total_f))
    tee.file.write("\n== summary: %d checks, %d PASS, %d FAIL ==\n"
                   % (len(collect), total_p, total_f))
    tee.close()
    if total_f:
        print("FAILING CHECKS:")
        for (cid, desc, ok) in collect:
            if not ok:
                print("   [%s] %s" % (cid, desc))
        sys.exit(1)


if __name__ == "__main__":
    main()
