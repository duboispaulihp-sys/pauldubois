def eps_factor(with_seed=True):
    """Q[eps]/(eps^2), deg eps = 1.  rel_by_deg keeps eps^2 even though
    top = 1 (external_product reads rel_by_deg, not the filtered GB)."""
    E = GradedRing(["eps"], [1], [{(2,): fr(1)}], 1)
    seeds = [(1, {(1,): fr(1)})] if with_seed else []
    return HarmlessCensus(E, seeds,
                          "Q[eps]/eps^2" + ("+seed" if with_seed else "-noseed"))


def eps2_factor(with_seed=True):
    """Q[eps, dlt]/(eps^2, eps*dlt, dlt^2), degs (1,1): first-order family
    over a 2-dimensional parameter disc; N^p = 0 for p >= 2, dim N^1 = 2."""
    E = GradedRing(["eps", "dlt"], [1, 1],
                   [{(2, 0): fr(1)}, {(1, 1): fr(1)}, {(0, 2): fr(1)}], 1)
    seeds = [(1, {(1, 0): fr(1)}), (1, {(0, 1): fr(1)})] if with_seed else []
    return HarmlessCensus(E, seeds, "N(eps,dlt)" + ("+seed" if with_seed else "-noseed"))


