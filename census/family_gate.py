def run_family(base, fam_hc2, verbose=True, collect=None, prefix="", T_hint=None):
    """Full gate battery for one base model and one nilpotent factor."""
    npass = nfail = 0
    tag = prefix

    def check(cid, desc, ok):
        nonlocal npass, nfail
        status = "PASS" if ok else "FAIL"
        print("   [%s] %s: %s" % (status, tag + cid, desc))
        if ok:
            npass += 1
        else:
            nfail += 1
        if collect is not None:
            collect.append((tag + cid, desc, ok))

    T_abs = abstract_top(base, hint=T_hint)
    base_ext = rebuild(base, T_abs)
    fam = external_product(base_ext, fam_hc2, "%s [%s]" % (base.name, fam_hc2.name))
    A = base_ext.A
    ftop = fam_hc2.A.top
    fw = fam_hc2.A.dim(1)          # dim N^1: 1 for eps, 2 for (eps, dlt)

    if verbose:
        print(" model %s: T_abs=%d, base dims %s, family top %d, factor %s (fw=%d)"
              % (base.name, T_abs, [A.dim(q) for q in range(T_abs + 1)],
                 T_abs + ftop, fam_hc2.name, fw))

    bc = {row["p"]: row for row in base_ext.census(T_abs)}
    fc = {row["p"]: row for row in fam.census(T_abs + ftop)}
    baseB = base_ext.algebra_B(T_abs)
    famB_all = fam.algebra_B(T_abs + ftop)

    def dz(q):
        return dimZ_at(base_ext, T_abs, q)

    # ---- Z-law ----
    ok = all(fc[p]["dim_Z"] == dz(p) + fw * dz(p - 1)
             for p in range(T_abs + ftop + 1))
    check("Z1", "Z-law dim Z^p(A_fam) = dim Z^p(A) + %d dim Z^{p-1}(A), all p" % fw, ok)

    # ---- B-law by teacher rank (independent computation) + inclusion ----
    n1 = A.n
    pad_r = (0,) * (fam.A.n - n1)
    okB, okI = True, True
    for p in range(T_abs + ftop + 1):
        fmonos = fam.A._monos(p)
        famB = famB_all[p]
        dimB_engine = _rank_of_family(famB, fmonos) if famB else 0
        teacher = []
        for b in baseB.get(p, []):
            teacher.append({m + pad_r: c for m, c in b.items()})
        for (q, s) in fam_hc2.seeds:
            if 0 <= p - q <= T_abs:
                sp = {(0,) * n1 + m: c for m, c in s.items()}
                for b in baseB[p - q]:
                    bp = {m + pad_r: c for m, c in b.items()}
                    teacher.append(fam.A.product_as_vector(p - q, bp, q, sp))
        rank_t = _rank_of_family(teacher, fmonos) if teacher else 0
        okB = okB and (dimB_engine == rank_t)
        if famB:
            r2 = _rank_of_family(teacher + famB, fmonos)
            okI = okI and (rank_t == r2)
    check("B1", "B-law dim B^p(A_fam) = dim B^p(A) + %d dim B^{p-1}(A)" % fw, okB)
    check("B2", "transport: engine B^p = span(base B^p padded + factor-images), all p", okI)

    # ---- slot law ----
    def w_base(p):
        if p < 0 or p > T_abs:
            return 0      # above the abstract top: Z = B = 0, so w = 0
        return bc[p]["w"]

    ok = all(fc[p]["w"] == w_base(p) + fw * w_base(p - 1)
             for p in range(T_abs + ftop + 1))
    check("W1", "slot law w_fam(p) = w_A(p) + %d w_A(p-1), all p" % fw, ok)

    # ---- VHC invariance ----
    left = all(fc[p]["w"] == 0 for p in range(T_abs + ftop + 1))
    right = all(bc[p]["w"] == 0 for p in range(T_abs + 1))
    check("V1", "model-VHC invariance: w_fam = 0 everywhere  <=>  w_A = 0 everywhere",
          left == right)

    # ---- hand anchors (engine vs. direct algebra in the docstring) ----
    if base.name == "P2" and fw == 1:
        ok = ([bc[p]["dim_Z"] for p in range(3)] == [1, 1, 1]
              and [fc[p]["dim_Z"] for p in range(4)] == [1, 2, 2, 1]
              and [fc[p]["w"] for p in range(4)] == [0, 0, 0, 0])
        check("H1", "P2 hand anchor: dims (1,1,1)->(1,2,2,1), w_fam = (0,0,0,0)", ok)
    if base.name == "slot" and fw == 1:
        ok = ([bc[p]["dim_Z"] for p in range(4)] == [1, 1, 2, 1]
              and [bc[p]["w"] for p in range(4)] == [0, 0, 1, 0]
              and [fc[p]["dim_Z"] for p in range(5)] == [1, 2, 3, 3, 1]
              and [fc[p]["w"] for p in range(5)] == [0, 0, 1, 1, 0])
        check("H2", "slot-ring hand anchor: Z (1,1,2,1)->(1,2,3,3,1), w (0,0,1,0)->(0,0,1,1,0)", ok)

    if verbose:
        print("      base w :", [bc[p]["w"] for p in range(T_abs + 1)])
        print("      fam  w :", [fc[p]["w"] for p in range(T_abs + ftop + 1)])
    return npass, nfail


def dimZ_at(base_ext, T_abs, q):
    """dim Z^q of the base at the ABSTRACT quotient: 0 for q > T_abs
    (abstract vanishing: for hinted tops this is the hand proof in the
    docstring; for probed tops, generation in degree 1 propagates the
    first zero)."""
    if q < 0 or q > T_abs:
        return 0
    return base_ext.A.dim(q)


def run_negative_control(base, verbose=True, collect=None, prefix="", T_hint=None):
    npass = nfail = 0
    tag = prefix

    def check(cid, desc, ok):
        nonlocal npass, nfail
        status = "PASS" if ok else "FAIL"
        print("   [%s] %s: %s" % (status, tag + cid, desc))
        if ok:
            npass += 1
        else:
            nfail += 1
        if collect is not None:
            collect.append((tag + cid, desc, ok))

    T_abs = abstract_top(base, hint=T_hint)
    base_ext = rebuild(base, T_abs)
    fam = external_product(base_ext, eps_factor(with_seed=False),
                           "%s [eps, NO seed]" % base.name)
    A = base_ext.A
    fc = {row["p"]: row for row in fam.census(T_abs + 1)}
    bc = {row["p"]: row for row in base_ext.census(T_abs)}

    def dz(q):
        return dimZ_at(base_ext, T_abs, q)

    # w_noseed(p) = w_A(p) + dim Z^{p-1}(A)   (Tate-dropped band)
    def w_base(p):
        if p < 0 or p > T_abs:
            return 0      # above the abstract top: Z = B = 0, so w = 0
        return bc[p]["w"]

    ok = all(fc[p]["w"] == w_base(p) + dz(p - 1)
             for p in range(T_abs + 2))
    check("N1", "Tate-dropped control: w_noseed(p) = w_A(p) + dim Z^{p-1}(A), all p", ok)

    # and the engine's B must NOT see the eps band anywhere (dB_noseed = dB_A)
    famB_all = fam.algebra_B(T_abs + 1)
    baseB = base_ext.algebra_B(T_abs)
    n1 = A.n
    pad_r = (0,) * (fam.A.n - n1)
    ok = True
    for p in range(T_abs + 2):
        fmonos = fam.A._monos(p)
        d_engine = _rank_of_family(famB_all[p], fmonos) if famB_all[p] else 0
        d_base = _rank_of_family([{m + pad_r: c for m, c in b.items()}
                                  for b in baseB.get(p, [])], fmonos) \
            if p <= T_abs else 0
        ok = ok and (d_engine == d_base)
    check("N2", "Tate-dropped: engine B^p(A_fam) = B^p(A) embedded, no eps band", ok)

    if verbose:
        print("      base w   :", [bc[p]["w"] for p in range(T_abs + 1)])
        print("      noseed w :", [fc[p]["w"] for p in range(T_abs + 2)])
    return npass, nfail


