"""family_gate.py -- Phase 11: the model-family gate for VHC (Note M, path P15).

Question explored here (machine half of Note M):

    Does the F-closure / Weil-slot pattern of the census model survive
    passage to FAMILIES in the model?

A first-order family is modeled by the dual-numbers-type ring
    A_fam = A (x) Q[eps]/(eps^2),   deg eps = 1 (cohomological degree 2),
built with `external_product` from harmless_census.py.  This models the
first-order neighborhood of a fiber in a family: eps is a cohomology
class in the base direction; eps^2 = 0 is the leading-order truncation.
A two-parameter variant uses N = Q[eps, dlt]/(eps^2, eps*dlt, dlt^2)
(degs (1,1)), so N^p = 0 for p >= 2 and dim N^1 = 2.

Semantics choices, all tested:

  (a) WITH the eps-seed(s): the factor's degree-1 generators are declared
      "B-stand-ins", i.e. the family direction's Hodge classes are
      algebraic in the model.  Then the subalgebra B_fam generated by the
      seeds is provably  B_A^p (x) eps * B_A^{p-1}  (Note M, Prop M.9) and:

          Z - LAW:     dim Z_fam^p = dim Z_A^p + fw * dim Z_A^{p-1}
          B - LAW:     dim B_fam^p = dim B_A^p + fw * dim B_A^{p-1}
          SLOT LAW:    w_fam(p)    = w_A(p)    + fw * w_A(p-1)
          INVARIANCE:  w_fam = 0 everywhere  <=>  w_A = 0 everywhere
                       (model-VHC transports through first-order families)
      with fw = dim N^1 (= 1 for eps, 2 for the (eps,dlt) factor).
      These laws are theorems of the model semantics, so the battery is a
      consistency certificate of the census implementation (Groebner
      basis, external-product padding directions, seed closure) on the
      fresh family rings -- the dim B check is done TWICE, once by the
      census engine's rank-incremental seed closure and once by an
      independent direct computation of the "teacher span"
          span{ B_A^p padded }  U  { eps-seed * b : b in B_A^{p-1} },
      and the two must agree degree by degree.

  (b) WITHOUT the eps-seed (negative control): the family direction
      carries NO algebraic class in B -- the model of a Tate-dropped
      direction.  Then B_fam = B_A (x) 1 and
          w_noseed(p) = w_A(p) + dim Z_A^{p-1},
      i.e. every fiber class acquires a full slot band.  The gate
      DETECTS exactly when the direction is Tate-dropped: the model
      analogue of "families can create Hodge classes that no cycle on
      the fiber sees" -- the phenomenon that makes P12 (smoothability)
      and P15 (first-order gate) nontrivial in nature.

Faithfulness caveat, handled by an explicit "abstract top": the demo
rings are presented with top_degree = the cohomological top of the
modeled variety, but the abstract quotient may be nonzero above that
top (e.g. the Weil-slot ring has h^3 =/= 0 while its census top is 2).
Since an N-graded ring generated in degree 1 satisfies
A^{d+1} = A^1 * A^d, vanishing propagates upward; for rings with higher
degree generators (the slot ring, with deg w = 2) the abstract top is
established by direct monomial-ideal computation
(relations h^4, w^2, hw are monomial, so every monomial of
degree >= 4 vanishes and A^3 = <h^3>).  Hand-derived values:

    P4 model:        T_abs = 4   (h^5 = 0)
    P2 model:        T_abs = 2   (g^3 = 0)
    slot ring:       T_abs = 3   (monomial relations kill deg >= 4)
    slot x P2:       T_abs = 5   (standard monomials h^a w^b g^c,
                                  a<=3, b<=1, c<=2, hw=0 => top h^3 g^2)
    matroids:        T_abs = rank-1 expected; probed, and generation in
                     degree 1 (all x_S) makes the zero propagate.

Hand-verification anchors (worked by direct algebra, independent of the
engine; asserted numerically below):

  P^2 model Q[g]/(g^3): dims (1,1,1).  Family Q[g,e]/(g^3,e^2):
  Z dims (1,2,2,1); with seeds {g,e}: B = (1,2,2,1); w = (0,0,0,0);
  slot law 0 = w_A(p)+w_A(p-1) with w_A = (0,0,0): trivial PASS.

  Weil-slot ring A = Q[h,w]/(h^4, w^2, hw), abstract top 3:
    dims A^p = (1,1,2,1), B (seed h) = (1,1,1,1), w_A = (0,0,1,0).
  Family A[eps] = Q[h,w,e]/(h^4, w^2, hw, e^2), top 4:
    Z dims = (1,2,3,3,1):  A^1 = <h,e>; A^2 = <w,h^2,he>;
      A^3 = <h^3, h^2 e, we>; A^4 = <h^3 e>   (w^2 = hw = e^2 = 0).
    B_fam (seeds h, e) = (1,2,2,2,1):  B^1 = <h,e>; B^2 = <h^2,he>;
      B^3 = <h^3, h^2 e>; B^4 = <h^3 e>.
    w_fam = (0,0,1,1,0) = (w_A(p) + w_A(p-1)): p=2: 1+0 = 1;
      p=3: 0+1 = 1; p=4: 0+0 = 0.  Hand PASS.

Run:
    python3 family_gate.py        # battery + results file (family_gate_results.txt)
"""

import sys
import time
from fractions import Fraction as fr

from harmless_census import (GradedRing, HarmlessCensus, external_product,
                             matroid_chow, _rank_of_family)


# ------------------------------------------------------------------
# helpers
# ------------------------------------------------------------------

class Tee(object):
    """Mirror stdout into a results file while printing."""

    def __init__(self, path):
        self.terminal = sys.stdout
        self.file = open(path, "w")

    def write(self, data):
        self.terminal.write(data)
        self.file.write(data)

    def flush(self):
        self.terminal.flush()
        self.file.flush()

    def close(self):
        self.file.close()


def _flatten_rels(ring):
    """All stored relations (rel_by_deg is kept unfiltered by top), in
    ascending-degree deterministic order."""
    out = []
    for deg in sorted(ring.rel_by_deg):
        out.extend(ring.rel_by_deg[deg])
    return out


def rebuild(hc, top):
    """Same presented ring and seeds, new (larger or equal) top_degree."""
    A = hc.A
    ring = GradedRing(A.names, A.vdeg, _flatten_rels(A), top)
    return HarmlessCensus(ring, hc.seeds, hc.name)


def abstract_top(base, hint=None):
    """Largest degree with nonzero dimension of the abstract quotient.
    If `hint` is given it is a hand-derived value (verified by one probe);
    otherwise the ring must be generated in degree 1 and we probe upward
    until the first zero degree, whose propagation upward is then a
    theorem (A^{d+1} = A^1 * A^d)."""
    A = base.A
    if hint is not None:
        r = rebuild(base, hint + 1)
        assert r.A.dim(hint + 1) == 0, \
            "hand-derived abstract top %d wrong for %s" % (hint, base.name)
        return hint
    assert all(d == 1 for d in A.vdeg), \
        "probe needs generation in degree 1 (all var degs 1): %s" % base.name
    T = A.top
    for k in range(1, 5):
        r = rebuild(base, T + k)
        if r.A.dim(T + k) == 0:
            return T + k - 1
    raise ValueError("abstract top not found within probe window: %s" % base.name)


