def base_models():
    """[(name, HarmlessCensus, T_abs_hint_or_None, note)]."""
    models = []

    ring = GradedRing(["h"], [1], [{(5,): fr(1)}], 4)
    models.append(("P4 model Q[h]/h^5",
                   HarmlessCensus(ring, [(1, {(1,): fr(1)})], "P4"),
                   4, "VHC-true fiber model"))

    ring = GradedRing(["g"], [1], [{(3,): fr(1)}], 2)
    models.append(("P2 model Q[g]/g^3",
                   HarmlessCensus(ring, [(1, {(1,): fr(1)})], "P2"),
                   2, "hand-verified anchor"))

    srels = [{(4, 0): fr(1)}, {(0, 2): fr(1)}, {(1, 1): fr(1)}]
    ring = GradedRing(["h", "w"], [1, 2], srels, 2)
    models.append(("Weil-slot ring",
                   HarmlessCensus(ring, [(1, {(1, 0): fr(1)})], "slot"),
                   3, "hand-verified anchor, one w-slot at p=2"))

    slot = GradedRing(["h", "w"], [1, 2], srels, 2)
    p2 = GradedRing(["g"], [1], [{(3,): fr(1)}], 2)
    prod = external_product(HarmlessCensus(slot, [(1, {(1, 0): fr(1)})], "slot"),
                            HarmlessCensus(p2, [(1, {(1,): fr(1)})], "P2"),
                            "slot x P2")
    models.append(("slot x P2 external product", prod,
                   5, "slot propagation under O4 (Cor 4.9)"))

    # matroids: seeds = ALL degree-1 flat divisors (every x_S is algebraic
    # in the model: a tautological class on the permutohedral toric variety)
    from itertools import combinations
    fano_lines = [[1, 2, 3], [1, 4, 5], [1, 6, 7], [2, 4, 6], [2, 5, 7],
                  [3, 4, 7], [3, 5, 6]]
    fano_ovals = [sorted({1, 2, 3, 4, 5, 6, 7} - {a, b, c})
                  for (a, b, c) in fano_lines]
    k4_circuits = [[1, 2, 4], [1, 3, 5], [2, 3, 6], [4, 5, 6],
                   [1, 3, 4, 6], [1, 2, 5, 6], [2, 3, 4, 5]]
    mroids = [
        ("U_{2,3}", [1, 2, 3], [[1, 2, 3]]),
        ("U_{2,4}", [1, 2, 3, 4], [list(c) for c in combinations(range(1, 5), 3)]),
        ("U_{3,5}", [1, 2, 3, 4, 5], [list(c) for c in combinations(range(1, 6), 4)]),
        ("Fano F_7", [1, 2, 3, 4, 5, 6, 7], fano_lines + fano_ovals),
        ("K4 graphic", list(range(1, 7)), k4_circuits),
    ]
    for (name, ground, circuits) in mroids:
        res = matroid_chow(ground, circuits, name)
        ring = res["ring"]
        seeds = [(1, {tuple(1 if j == i else 0 for j in range(len(ring.names))): fr(1)})
                 for i in range(len(ring.names))]
        models.append(("matroid %s Chow" % name,
                       HarmlessCensus(ring, seeds, name),
                       None, "FY/Bergman presentation, %d flat divisors" % len(seeds)))

    return models


