def matroid_from_circuits(ground, circuits):
    """Matroid from a list of circuits.  Returns (E, flats, rank_fn)."""
    E = frozenset(ground)
    circuits = [frozenset(c) for c in circuits]
    import itertools as it

    def cl(S):
        cur = frozenset(S)
        while True:
            add = None
            for e in E:
                if e in cur:
                    continue
                for C in circuits:
                    if e in C and C <= (cur | {e}):
                        add = e
                        break
                if add is not None:
                    break
            if add is None:
                return cur
            cur = cur | {add}

    elems = sorted(E)
    flats = set()
    for k in range(len(elems) + 1):
        for sub in it.combinations(elems, k):
            flats.add(cl(frozenset(sub)))
    flats = sorted(flats, key=lambda f: (len(f), sorted(f)))

    def r(S):
        """Max size of a circuit-free subset of S."""
        best = 0
        elemsS = sorted(S)
        for k in range(len(elemsS) + 1):
            for sub in it.combinations(elemsS, k):
                s = frozenset(sub)
                if not any(C <= s for C in circuits):
                    best = max(best, len(sub))
        return best

    return E, flats, r


def chow_presentation(E, flats):
    """Feichtner-Yuzvinsky/Bergman presentation:
       A^*(M) = Q[x_S : nonempty proper flats] /
                ( x_S x_T for incomparable S,T ;
                  sum_{S contains i} x_S - sum_{S contains j} x_S ).
    """
    proper = [f for f in flats if 0 < len(f) < len(E)]
    names = ["x" + "".join(map(str, sorted(f))) for f in proper]
    degs = [1] * len(proper)
    rels = []
    for a in range(len(proper)):
        for b in range(a + 1, len(proper)):
            f, g = proper[a], proper[b]
            if not (f <= g or g <= f):
                mono = [0] * len(proper)
                mono[a] = 1
                mono[b] = 1
                rels.append({tuple(mono): fr(1)})
    for i in E:
        for j in E:
            if i < j:
                rel = {}
                for k, f in enumerate(proper):
                    c = (1 if i in f else 0) - (1 if j in f else 0)
                    if c:
                        mono = [0] * len(proper)
                        mono[k] = 1
                        rel[tuple(mono)] = fr(c)
                if rel:
                    rels.append(rel)
    return names, degs, rels


def matroid_chow(ground, circuits, name):
    E, flats, r = matroid_from_circuits(ground, circuits)
    rk = r(E)
    names, degs, rels = chow_presentation(E, flats)
    top = max(0, rk - 1)
    if not names:
        ring = GradedRing(["x"], [1], [], top)
    else:
        ring = GradedRing(names, degs, rels, top)
    return {"name": name, "rank": rk, "n_flats": len(flats),
            "ring": ring,
            "dims": [(p, ring.dim(p)) for p in range(top + 1)]}


def pd_check(res):
    """Poincare-duality certificate: the pairing A^k x A^{d-k} -> A^d = Q
    is nondegenerate for every k (d = top).  Returns list of
    (k, dim A^k, pairing rank) or None."""
    ring = res["ring"]
    d = ring.top
    if ring.dim(d) != 1:
        return None
    topb = ring.basis(d)[0]
    out = []
    for k in range(d + 1):
        b1 = ring.basis(k)
        b2 = ring.basis(d - k)
        rows = []
        for m1 in b1:
            row = []
            for m2 in b2:
                prod = ring.mult(k, m1, d - k, m2)
                row.append(prod.get(topb, fr(0)))
            rows.append(row)
        out.append((k, len(b1), LinAlg.rank(rows)))
    return out


def hr_spot_check(res, trials=5, seed=0):
    """Experimental Hodge-Riemann scan at k = 1 (requires d = top >= 3 so
    that primitive divisor classes exist).  For random positive 'Kahler
    candidates' a = sum c_i x_S (c_i >= 1; need not actually be Kahler --
    failures here indict the experimental setup, never the mathematics), we
    solve the primitive condition a^{d-1} xi = 0 exactly inside A^1 (unless
    the Lefschetz map is injective, in which case A^1 is primitive-free and
    the scan is vacuous), draw random primitive xi, and check
        q_a(xi, xi) = integral a^{d-2} xi^2 > 0.
    """
    ring = res["ring"]
    d = ring.top
    if d < 3 or ring.dim(d) != 1 or ring.dim(1) == 0:
        return None
    rng = random.Random(seed)
    topb = ring.basis(d)[0]
    nz = len(ring.names)
    b1 = ring.basis(1)
    idx1 = {m: i for i, m in enumerate(b1)}

    def rand_a():
        v = {}
        for m in b1:
            mono = [0] * nz
            mono[idx1[m]] = 1  # placeholder replaced below
            v[m] = fr(rng.randint(1, 4)) + fr(1, 10)
        return ring._reduce(v, 1)

    def pow_of(a, e):
        cur, cur_deg = ring.unit(), 0
        for _ in range(e):
            cur = ring.product_as_vector(cur_deg, cur, 1, a)
            cur_deg += 1
        return cur

    stats = {"trials": trials, "kahler_tried": 0, "passed": 0,
             "failed": 0, "primitive_dim": 0, "vacuous": 0}
    for _ in range(trials):
        a = rand_a()
        a_dm1 = pow_of(a, d - 1)
        # linear functional xi -> (a^{d-1} xi) top coefficient, on A^1
        row = []
        for m in b1:
            px = ring.product_as_vector(1, m, d - 1, a_dm1)
            row.append(px.get(topb, fr(0)))
        if LinAlg.rank([row]) == 0:
            stats["vacuous"] += 1
            continue
        ker = None  # lazy: build kernel basis of the 1-row functional over Q
        ker = []
        n = len(b1)
        # kernel of a single nonzero functional: n-1 vectors
        if all(x == 0 for x in row):
            continue
        pc = next(i for i, x in enumerate(row) if x != 0)
        for j in range(n):
            if j == pc:
                continue
            vec = [fr(0)] * n
            vec[j] = fr(1)
            vec[pc] = -row[j] / row[pc]
            ker.append(vec)
        stats["primitive_dim"] = len(ker)
        if not ker:
            stats["vacuous"] += 1
            continue
        stats["kahler_tried"] += 1
        for _rep in range(3):
            coef = [fr(rng.randint(-5, 5)) for _ in ker]
            if all(c == 0 for c in coef):
                coef[0] = fr(1)
            xi_vec = [sum(c * v[i] for c, v in zip(coef, ker))
                      for i in range(n)]
            xi = {m: xi_vec[i] for i, m in enumerate(b1)}
            xi = {m: c for m, c in xi.items() if c != 0}
            if not xi:
                continue
            a_dm2 = pow_of(a, d - 2)
            vol = ring.product_as_vector(d - 2, a_dm2, 1,
                                         ring.product_as_vector(1, xi, 1, xi))
            val = vol.get(topb, fr(0))
            if val > 0:
                stats["passed"] += 1
            else:
                stats["failed"] += 1
    return stats


