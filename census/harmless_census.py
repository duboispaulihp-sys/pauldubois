def demo_all():
    print("== demo 1: Hodge ring Q[h]/(h^5), model of P^4 ==")
    ring = GradedRing(["h"], [1], [{(5,): fr(1)}], 4)
    hc = HarmlessCensus(ring, [(1, {(1,): fr(1)})], "Q[h]/(h^5)")
    HarmlessCensus.print_census(hc.census(),
                                "P^4 model: divisors generate everything")

    print("== demo 2: Weil-slot ring A = Q[h,w]/(h^4, w^2, h w) ==")
    print("   (deg h = 1 i.e. cohomological 2; deg w = 2 i.e. cohomological 4;")
    print("    models a Hodge ring with one non-divisorial codimension-2 class)")
    srels = [
        {(4, 0): fr(1)},   # h^4 = 0
        {(0, 2): fr(1)},   # w^2 = 0
        {(1, 1): fr(1)},   # h w = 0
    ]
