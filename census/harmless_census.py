def _rank_of_family(family, monos):
    if not family:
        return 0
    idx = {m: i for i, m in enumerate(monos)}
    rows = []
    for v in family:
        row = [fr(0)] * len(monos)
        for m, c in v.items():
            row[idx[m]] += c
        rows.append(row)
    return LinAlg.rank(rows)


class HarmlessCensus:
    def __init__(self, ring, seeds, name="unnamed"):
        self.A = ring
        self.name = name
        self.seeds = []
        for (p, vec) in seeds:
            vec = {tuple(m): fr(c) for m, c in vec.items()}
            self.seeds.append((p, ring._reduce(vec, p)))

    def algebra_B(self, max_deg=None):
        """Return {p: [vector dicts]} spanning B^p over Q (the subalgebra
        generated by the seeds and the unit)."""
        max_deg = self.A.top if max_deg is None else max_deg
        B = {p: [] for p in range(max_deg + 1)}
        B[0].append(self.A.unit())
        improved = True
        while improved:
            improved = False
            for p in range(max_deg + 1):
                for v in list(B[p]):
                    for (q, s) in self.seeds:
                        d = p + q
                        if d > max_deg:
                            continue
                        w = self.A.product_as_vector(p, v, q, s)
                        if not w:
                            continue
                        m = self.A._monos(d)
                        if _rank_of_family(B[d] + [w], m) > _rank_of_family(B[d], m):
                            B[d].append(w)
                            improved = True
        return B

    def census(self, max_deg=None):
        max_deg = self.A.top if max_deg is None else max_deg
        B = self.algebra_B(max_deg)
        table = []
        for p in range(max_deg + 1):
            dimZ = self.A.dim(p)
            dimB = _rank_of_family(B[p], self.A._monos(p))
            table.append({"p": p, "dim_Z": dimZ, "dim_B": dimB,
                          "w": dimZ - dimB})
        return table

    @staticmethod
    def print_census(table, title):
        print("== census: %s ==" % title)
        print("   p   dim_Z^p   dim_B^p   w(p)")
        for row in table:
            print("   %-3d %-9d %-9d %d" %
                  (row["p"], row["dim_Z"], row["dim_B"], row["w"]))
        slots = [row for row in table if row["w"] > 0]
        if not slots:
            print("   distance to HC_Q (in this model): 0  (w = 0 in all degrees)")
        else:
            print("   Weil slots at: " +
                  ", ".join("p=%d (w=%d)" % (r["p"], r["w"]) for r in slots))
        print()


def external_product(hc1, hc2, name="product"):
    """A1 (x) A2 as a GradedRing on the union of variables (relations from
    both factors on disjoint variables), seeds pulled back from both."""
    A1, A2 = hc1.A, hc2.A
    names = list(A1.names) + list(A2.names)
    vdeg = list(A1.vdeg) + list(A2.vdeg)
    off2 = len(A1.names)
    pad_r = (0,) * len(A2.vdeg)
    rels = []
    for deg in A1.rel_by_deg:
        for rel in A1.rel_by_deg[deg]:
            rels.append({m + pad_r: c for m, c in rel.items()})
    for deg in A2.rel_by_deg:
        for rel in A2.rel_by_deg[deg]:
            rels.append({(0,) * off2 + m: c for m, c in rel.items()})
    top = A1.top + A2.top
    prod = GradedRing(names, vdeg, rels, top)
    pad_r = (0,) * len(A2.vdeg)
    seeds = []
    for (p, vec) in hc1.seeds:
        seeds.append((p, {m + pad_r: c for m, c in vec.items()}))
    for (p, vec) in hc2.seeds:
        seeds.append((p, {(0,) * off2 + m: c for m, c in vec.items()}))
    return HarmlessCensus(prod, seeds, name=name)


