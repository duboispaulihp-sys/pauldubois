"""
harmless_census.py
==================

Computational machinery for the F-closure / harmless-subgroup census
(companion code to the notes "F-closure beyond the toolkit" and
"The tropical program").

Implemented over exact rational arithmetic (fractions.Fraction,
no external dependencies):

  1. LinAlg: exact ranks / Gaussian elimination over Q.
  2. GradedRing: a graded commutative Q-algebra presented as
         A = Q[x_0,...,x_{m-1}]/(homogeneous relations),
     computed by exact homogeneous Groebner bases (Buchberger, graded
     lex order, degree-capped: only Groebner elements of degree <= top are
     needed for the quotient up to degree `top`, since the ideal is
     homogeneous).  Ring degree p corresponds to cohomological degree 2p
     ("codimension p"); a divisor class has ring degree 1.
     Provides graded pieces, bases, dims, and the full multiplication table.
  3. HarmlessCensus: given such a ring (a stand-in for the rational Hodge
     ring Hdg^*(X), with Z^p := A^p) and a list of "seed" elements
     (stand-in for B_Z: e.g. the divisor classes), computes
         B^p  = degree-p piece of the subalgebra generated by the seeds,
         w(p) = dim A^p - dim B^p   ("Weil slots"),
     with w = 0 in every degree iff the modeled variety satisfies HC_Q in
     this model.  External products can be formed (operation (O4)),
     demonstrating computationally how slots propagate (Corollaries 4.8/4.9
     of the F-closure note).
  4. Matroid pillar: circuits -> flats -> the Feichtner-Yuzvinsky /
     Bergman presentation
         A^*(M) = Q[x_S : nonempty proper flats S] /
                  ( x_S x_T for incomparable S,T ;
                    sum_{S contains i} x_S - sum_{S contains j} x_S ),
     the Chow ring of the permutohedral refinement of the Bergman fan
     (a smooth projective toric variety; Adiprasito-Huh-Katz prove Hodge-
     Riemann relations for it, hence HC_Q in generated form).  The code
     computes graded dims and validates Poincare duality of the top
     pairing as an internal-consistency certificate of the presentation.
  5. hr_spot_check: an experimental Hodge-Riemann scan on random positive
     divisor combinations; failures here indict the experimental setup
     (random positive combinations need not be Kahler), never the
     mathematics.

Run:
    python3 harmless_census.py     # demos + demo census output
    python3 test_census.py         # unit tests
"""

from fractions import Fraction
from itertools import combinations
import random

fr = Fraction


# ------------------------------------------------------------------
# 1. Exact linear algebra over Q
# ------------------------------------------------------------------

class LinAlg:
    @staticmethod
    def rref(rows):
        """Reduced row echelon form over Q.
        rows: list of lists of Fraction.  Returns (rref_rows, pivots)."""
        rows = [list(r) for r in rows]
        if not rows:
            return [], []
        ncols = len(rows[0])
        pivots = []
        r = 0
        for c in range(ncols):
            piv = None
            for i in range(r, len(rows)):
                if rows[i][c] != 0:
                    piv = i
                    break
            if piv is None:
                continue
            rows[r], rows[piv] = rows[piv], rows[r]
            pv = rows[r][c]
            rows[r] = [x / pv for x in rows[r]]
            for i in range(len(rows)):
                if i != r and rows[i][c] != 0:
                    f = rows[i][c]
                    rows[i] = [a - f * b for a, b in zip(rows[i], rows[r])]
            pivots.append(c)
            r += 1
            if r == len(rows):
                break
        rows = [row for row in rows if any(x != 0 for x in row)]
        return rows, pivots

    @staticmethod
    def rank(rows):
        _, piv = LinAlg.rref(rows)
        return len(piv)


# ------------------------------------------------------------------
# 2. Graded rings by homogeneous Groebner bases
# ------------------------------------------------------------------

def _mono_deg(mono, vdeg):
    return sum(vdeg[i] * e for i, e in enumerate(mono) if e)


def _mono_add(m1, m2, n):
    c = [0] * n
    for i, e in enumerate(m1):
        c[i] += e
    for i, e in enumerate(m2):
        c[i] += e
    return tuple(c)


def _mono_key(mono):
    """Graded lex: total degree, then lex on the reversed tuple."""
    return (sum(mono), tuple(reversed(mono)))


class GradedRing:
    """A = Q[x_i]/(homogeneous relations), Buchberger-GB computed."""

    def __init__(self, names, var_degs, relations, top_degree):
        assert len(names) == len(var_degs)
        self.names = list(names)
        self.vdeg = [int(d) for d in var_degs]
        self.n = len(self.vdeg)
        self.top = int(top_degree)
        self.zero = (0,) * self.n
        self.rel_by_deg = {}
        rels = []
        for rel in relations:
            rel = {tuple(m): fr(c) for m, c in rel.items()}
            rel = {m: c for m, c in rel.items() if c != 0}
            if rel:
                d = _mono_deg(next(iter(rel)), self.vdeg)
                assert all(_mono_deg(m, self.vdeg) == d for m in rel), \
                    "inhomogeneous relation: %s" % rel
                self.rel_by_deg.setdefault(d, []).append(rel)
                rels.append(rel)
        # discard relations of degree > top (irrelevant for graded pieces
        # up to top, since the ideal is homogeneous)
        rels = [r for r in rels
                if _mono_deg(max(r, key=lambda m: _mono_key(m)), self.vdeg) <= self.top]
        self._gb = self._buchberger(rels)
        # per degree: rref of the GB elements of that degree in monomial coords
        self._rows = {}
        self._pivots = {}
        self._basis = {}
        for p in range(self.top + 1):
            monos = sorted(self._monos(p), key=_mono_key)
            idx = {m: i for i, m in enumerate(monos)}
            rows = []
            for g in self._gb:
                dg = _mono_deg(max(g, key=lambda m: _mono_key(m)), self.vdeg)
                if dg > p:
                    continue
                # all monomial multiples t*g of degree p (initial-ideal
                # saturation: needed so relations propagate across degrees)
                for t in self._monos(p - dg):
                    row = [fr(0)] * len(monos)
                    ok = True
                    for m, c in g.items():
                        mt = _mono_add(m, t, self.n)
                        if mt not in idx:
                            ok = False
                            break
                        row[idx[mt]] += c
                    if ok and any(x != 0 for x in row):
                        rows.append(row)
            rref, piv = LinAlg.rref(rows) if rows else ([], [])
            self._rows[p] = rref
            self._pivots[p] = set(piv)
            pivset = set(piv)
            self._basis[p] = [m for i, m in enumerate(monos) if i not in pivset]
        # multiplication table on basis elements (only where p+q <= top)
        self._mult = {}
        for p in range(self.top + 1):
            for m1 in self._basis[p]:
                for q in range(self.top + 1 - p):
                    for m2 in self._basis[q]:
                        prod = _mono_add(m1, m2, self.n)
                        self._mult[(p, m1, q, m2)] = self._reduce({prod: fr(1)}, p + q)

    # -- monomials --
    def _monos(self, p):
        if p in getattr(self, "_monos_cache", {}):
            return self._monos_cache[p]
        out = []

        def rec(i, rem, cur):
            if i == self.n:
                if rem == 0:
                    out.append(tuple(cur))
                return
            d = self.vdeg[i]
            for k in range(rem // d + 1):
                rec(i + 1, rem - k * d, cur + [k])

        rec(0, p, [])
        if not hasattr(self, "_monos_cache"):
            self._monos_cache = {}
        self._monos_cache[p] = out
        return out

    # -- Buchberger --
    def _lead(self, g):
        return max(g, key=lambda m: _mono_key(m))

    def _lcm_monomial(self, a, b):
        return tuple(max(x, y) for x, y in zip(a, b))

    def _divides(self, a, b):
        return all(x <= y for x, y in zip(a, b))

    def _mono_div(self, a, b):
        return tuple(x - y for x, y in zip(a, b))

    def _reduce_poly(self, poly, gb):
        """Reduce a dict-poly modulo gb (homogeneous; all same degree
        handled term by term). Returns reduced dict."""
        poly = {m: c for m, c in poly.items() if c != 0}
        while poly:
            m = max(poly, key=lambda k: _mono_key(k))
            c = poly[m]
            reducible = None
            for g in gb:
                lm = self._lead(g)
                if self._divides(lm, m):
                    reducible = (g, lm)
                    break
            if reducible is None:
                break
            g, lm = reducible
            t = self._mono_div(m, lm)
            g_lead = g[lm]
            coef = c / g_lead
            for mm, cc in g.items():
                nt = _mono_add(mm, t, self.n)
                poly[nt] = poly.get(nt, fr(0)) - coef * cc
            poly = {mm: cc for mm, cc in poly.items() if cc != 0}
        return poly

    def _buchberger(self, gens):
        gb = [dict(g) for g in gens]
        gb = [g for g in gb if g]
        while True:
            added = False
            for i in range(len(gb)):
                for j in range(i + 1, len(gb)):
                    li, lj = self._lead(gb[i]), self._lead(gb[j])
                    l = self._lcm_monomial(li, lj)
                    if _mono_deg(l, self.vdeg) > self.top:
                        continue
                    ti = self._mono_div(l, li)
                    tj = self._mono_div(l, lj)
                    s = {}
                    ci = gb[i][li]
                    cj = gb[j][lj]
                    for m, c in gb[i].items():
                        nm = _mono_add(m, ti, self.n)
                        s[nm] = s.get(nm, fr(0)) + c / ci
                    for m, c in gb[j].items():
                        nm = _mono_add(m, tj, self.n)
                        s[nm] = s.get(nm, fr(0)) - c / cj
                    s = {m: c for m, c in s.items() if c != 0}
                    if not s:
                        continue
                    if _mono_deg(max(s, key=lambda m: _mono_key(m)), self.vdeg) > self.top:
                        continue
                    red = self._reduce_poly(s, gb)
                    if red:
                        gb.append(red)
                        added = True
            if not added:
                break
        return gb

    def _reduce(self, vec, deg):
        """vec: dict monomial->coef in ring degree `deg`; canonical reduced
        representative supported on the basis (non-initial) monomials."""
        monos = sorted(self._monos(deg), key=_mono_key)
        idx = {m: i for i, m in enumerate(monos)}
        v = [fr(0)] * len(monos)
        for m, c in vec.items():
            if m in idx:
                v[idx[m]] += c
        for row in self._rows[deg]:
            pc = next(i for i, x in enumerate(row) if x != 0)
            c = v[pc]
            if c != 0:
                v = [a - c * b for a, b in zip(v, row)]
        return {m: v[idx[m]] for m in monos if v[idx[m]] != 0}

    # -- public API --
    def unit(self):
        return {self.zero: fr(1)}

    def dim(self, p):
        return len(self._basis[p])

    def basis(self, p):
        return list(self._basis[p])

    def mult(self, p, m1, q, m2):
        return self._mult[(p, m1, q, m2)]

    def product_as_vector(self, p, v1, q, v2):
        out = {}
        for m1, c1 in v1.items():
            for m2, c2 in v2.items():
                for m3, c3 in self._mult[(p, m1, q, m2)].items():
                    out[m3] = out.get(m3, fr(0)) + c1 * c2 * c3
        return {m: c for m, c in out.items() if c != 0}

    def total_dim(self):
        return sum(self.dim(p) for p in range(self.top + 1))


